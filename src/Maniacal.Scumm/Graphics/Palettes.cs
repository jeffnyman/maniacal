using Daventry.Core.Graphics;

namespace Maniacal.Scumm.Graphics;

/// <summary>The fixed palettes of the releases. Mirrors the tables in ScummVM's <c>ScummEngine::resetPalette</c>.</summary>
public static class Palettes
{
    /// <summary>The 16 EGA colours the DOS releases draw with. Mirrors <c>tableEGAPalette</c>.</summary>
    public static ReadOnlySpan<Rgb> Ega => EgaColors;

    /// <summary>
    /// The C64 colour numbers of version 1 rooms, as the EGA colours the DOS release shows them.
    /// Mirrors the "MM: EGA, Tandy, MCGA, CGA Composite" row of <c>setV1ColorTable</c>.
    /// </summary>
    public static ReadOnlySpan<byte> ManiacV1ToEga =>
        [0x00, 0x0F, 0x04, 0x03, 0x05, 0x02, 0x01, 0x0E, 0x0C, 0x06, 0x0C, 0x08, 0x07, 0x0A, 0x09, 0x08];

    private static readonly Rgb[] EgaColors =
    [
        new(0x00, 0x00, 0x00), new(0x00, 0x00, 0xAA), new(0x00, 0xAA, 0x00), new(0x00, 0xAA, 0xAA),
        new(0xAA, 0x00, 0x00), new(0xAA, 0x00, 0xAA), new(0xAA, 0x55, 0x00), new(0xAA, 0xAA, 0xAA),
        new(0x55, 0x55, 0x55), new(0x55, 0x55, 0xFF), new(0x55, 0xFF, 0x55), new(0x55, 0xFF, 0xFF),
        new(0xFF, 0x55, 0x55), new(0xFF, 0x55, 0xFF), new(0xFF, 0xFF, 0x55), new(0xFF, 0xFF, 0xFF),
    ];
}
