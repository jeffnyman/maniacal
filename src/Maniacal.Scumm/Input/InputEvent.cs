namespace Maniacal.Scumm.Input;

/// <summary>What an <see cref="InputEvent"/> reports.</summary>
public enum InputEventType
{
    /// <summary>No event.</summary>
    None = 0,

    /// <summary>A key went down, or repeated while held.</summary>
    KeyDown,

    /// <summary>A key came up.</summary>
    KeyUp,

    /// <summary>The mouse moved.</summary>
    MouseMove,

    /// <summary>A mouse button went down.</summary>
    MouseDown,

    /// <summary>A mouse button came up.</summary>
    MouseUp,

    /// <summary>The host asked the engine to shut down (window closed, Ctrl+C, and so on).</summary>
    Quit,
}

/// <summary>A single input event delivered by the host. Mouse coordinates are in framebuffer pixels.</summary>
public readonly record struct InputEvent(InputEventType Type)
{
    /// <summary>The key, for key events.</summary>
    public Key Key { get; init; }

    /// <summary>The modifier keys held, for key events.</summary>
    public KeyModifiers Modifiers { get; init; }

    /// <summary>The printable character for a key event, or NUL. Mirrors ScummVM's KeyState.ascii.</summary>
    public char Ascii { get; init; }

    /// <summary>The mouse's column, for mouse events.</summary>
    public int X { get; init; }

    /// <summary>The mouse's row, for mouse events.</summary>
    public int Y { get; init; }

    /// <summary>The button, for button events.</summary>
    public MouseButton Button { get; init; }

    /// <summary>True for key events generated by the operating system's key repeat.</summary>
    public bool Repeat { get; init; }

    /// <summary>The host asks the engine to shut down.</summary>
    public static InputEvent Quit => new(InputEventType.Quit);

    /// <summary>A key going down, with the modifiers held and the character it types.</summary>
    public static InputEvent KeyDown(Key key, KeyModifiers modifiers = KeyModifiers.None, char ascii = default, bool repeat = false)
        => new(InputEventType.KeyDown) { Key = key, Modifiers = modifiers, Ascii = ascii, Repeat = repeat };

    /// <summary>A key coming up.</summary>
    public static InputEvent KeyUp(Key key, KeyModifiers modifiers = KeyModifiers.None, char ascii = default)
        => new(InputEventType.KeyUp) { Key = key, Modifiers = modifiers, Ascii = ascii };

    /// <summary>The mouse moving to a pixel.</summary>
    public static InputEvent MouseMove(int x, int y) => new(InputEventType.MouseMove) { X = x, Y = y };

    /// <summary>A mouse button going down at a pixel.</summary>
    public static InputEvent MouseDown(MouseButton button, int x, int y)
        => new(InputEventType.MouseDown) { Button = button, X = x, Y = y };

    /// <summary>A mouse button coming up at a pixel.</summary>
    public static InputEvent MouseUp(MouseButton button, int x, int y)
        => new(InputEventType.MouseUp) { Button = button, X = x, Y = y };
}
