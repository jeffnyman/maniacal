"""Generates Palettes.g.cs from ScummVM's engines/scumm/palette.cpp.

Keeps the palettes of Maniac Mansion's DOS and C64 releases (tableEGAPalette, and the VICE-based
branch of tableC64Palette with its 17th colour), and the rows of setV1ColorTable's v1ColorMaps
those releases draw rooms with. Run from the repository root:

    python tools/port_palettes.py ../scummvm/engines/scumm/palette.cpp > src/Maniacal.Scumm/Graphics/Palettes.g.cs
"""

import re
import sys

# the rows of v1ColorMaps by their comments
COLOR_MAPS = [
    ("C-64", "C64Colors", "The C64's colour numbers, kept as they are (the \"C-64\" row of <c>setV1ColorTable</c>)."),
    ("MM: EGA", "ManiacV1EgaColors", "The C64 colour numbers of version 1 rooms as the EGA colours the DOS release shows them (the \"MM: EGA, Tandy, MCGA, CGA Composite\" row of <c>setV1ColorTable</c>)."),
]


def body(source, name):
    match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if match is None:
        sys.exit(f"{name} not found")
    return match.group(1)


def numbers(text):
    text = re.sub(r"//[^\n]*", "", text)
    return [int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]{2})", text)]


def palette(source, name):
    text = body(source, name)
    # take the branch ScummVM builds (#if 1), and what follows the #endif
    text = re.sub(r"#else.*?#endif", "", text, flags=re.S)
    text = re.sub(r"#if 1[^\n]*", "", text)
    values = numbers(text)
    return [values[i:i + 3] for i in range(0, len(values), 3)]


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    maps_text = re.search(r"v1ColorMaps\[5\]\[16\]\s*=\s*\{(.*?)\n\t\};", source, re.S).group(1)

    print("// <auto-generated>")
    print("// Generated by tools/port_palettes.py from ScummVM's engines/scumm/palette.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Graphics;")
    print()
    print("public static partial class Palettes")
    print("{")
    for name, field, summary in [
        ("tableEGAPalette", "EgaColors", "The 16 EGA colours (<c>tableEGAPalette</c>)."),
        ("tableC64Palette", "C64Rgb", "The 16 C64 colours of ScummVM's VICE-based palette, and a 17th for the inventory and sentence line (<c>tableC64Palette</c>)."),
    ]:
        print(f"    /// <summary>{summary}</summary>")
        print(f"    private static readonly Rgb[] {field} =")
        print("    [")
        colors = palette(source, name)
        for start in range(0, len(colors), 4):
            print("        " + " ".join(f"new(0x{r:02X}, 0x{g:02X}, 0x{b:02X})," for r, g, b in colors[start:start + 4]))
        print("    ];")
        print()

    rows = re.findall(r"//\s*([^\n]*)\n\s*\{([^}]*)\}", maps_text)
    for i, (label, field, summary) in enumerate(COLOR_MAPS):
        values = next((numbers(v) for c, v in rows if c.startswith(label)), None)
        if values is None:
            sys.exit(f"colour map {label} not found")
        if i > 0:
            print()
        print(f"    /// <summary>{summary}</summary>")
        print(f"    private static readonly byte[] {field} =")
        print("    [")
        print("        " + " ".join(f"0x{v:02X}," for v in values))
        print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
