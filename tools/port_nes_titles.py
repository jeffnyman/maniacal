"""Generates NesTitleTables.g.cs from ScummVM's engines/scumm/gfx_nes.cpp.

Keeps what playNESTitleScreens shows the NES's two title screens with: how long each stays, the
second's eight sparkles (where they appear, how often one appears and how fast it twinkles) and
the twinkle sound each one starts, four steps of a square channel's registers. Run from the
repository root:

    python tools/port_nes_titles.py ../scummvm/engines/scumm/gfx_nes.cpp > src/Maniacal.Scumm/Graphics/NesTitleTables.g.cs
"""

import re
import sys


def numbers(text):
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.DOTALL)
    return [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\d+", text)]


def array(source, name, size):
    match = re.search(r"\b" + re.escape(name) + r"\[" + re.escape(size) + r"\]\s*=\s*\{(.*?)\};", source, re.DOTALL)
    if match is None:
        sys.exit(f"{name} not found")
    return numbers(match.group(1))


def constant(source, pattern, name):
    match = re.search(pattern, source)
    if match is None:
        sys.exit(f"{name} not found")
    return int(match.group(1), 0)


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    twinkles = array(source, "kTwinkleGroups", "8][4][6")
    xs = array(source, "sparklePosX", "8")
    ys = array(source, "sparklePosY", "8")
    if len(twinkles) != 8 * 4 * 6 or len(xs) != 8 or len(ys) != 8:
        sys.exit("unexpected table sizes")

    anim = constant(source, r"animFramesPerStep\s*=\s*(\d+)", "animFramesPerStep")
    spawn = constant(source, r"spawnFramesPerSparkle\s*=\s*(\d+)", "spawnFramesPerSparkle")
    first = constant(source, r"nesTitleWaitOrSkip\(_system,\s*(\d+)u?\)", "the first title's wait")
    second = constant(source, r"nesTitle2WaitOrSkipWithSpriteAnim\([^;]*?,\s*(\d+)u?,\s*nesFile", "the second title's wait")
    tick = constant(source, r"elapsedMs\s*/\s*(\d+)", "the sparkles' tick")

    w = []
    w.append("// <auto-generated>")
    w.append("// Generated by tools/port_nes_titles.py from ScummVM's engines/scumm/gfx_nes.cpp. Do not edit.")
    w.append("// </auto-generated>")
    w.append("")
    w.append("namespace Maniacal.Scumm.Graphics;")
    w.append("")
    w.append("internal static class NesTitleTables")
    w.append("{")
    w.append("    /// <summary>How long each title screen stays, in milliseconds (<c>playNESTitleScreens</c>).</summary>")
    w.append(f"    public static readonly int[] WaitMilliseconds = [{first}, {second}];")
    w.append("")
    w.append("    /// <summary>The milliseconds the sparkles count their frames in (<c>elapsedMs / 16</c>).</summary>")
    w.append(f"    public const int TickMilliseconds = {tick};")
    w.append("")
    w.append("    /// <summary>The frames between a sparkle's pictures, less one (<c>animFramesPerStep</c>).</summary>")
    w.append(f"    public const int FramesPerPicture = {anim};")
    w.append("")
    w.append("    /// <summary>The frames between one sparkle and the next, less one (<c>spawnFramesPerSparkle</c>).</summary>")
    w.append(f"    public const int FramesPerSparkle = {spawn};")
    w.append("")
    w.append("    /// <summary>Where each of the eight sparkles appears, its top left on the screen (<c>sparklePosX</c>, <c>sparklePosY</c>).</summary>")
    w.append("    public static readonly (int X, int Y)[] Sparkles =")
    w.append("    [")
    for i in range(8):
        w.append(f"        (0x{xs[i]:02X}, 0x{ys[i]:02X}),")
    w.append("    ];")
    w.append("")
    w.append("    /// <summary>")
    w.append("    /// The twinkle each sparkle starts: four steps of six bytes, a square channel's register")
    w.append("    /// writes and the frames they last (<c>kTwinkleGroups</c>), sparkle after sparkle.")
    w.append("    /// </summary>")
    w.append("    public static readonly byte[] Twinkles =")
    w.append("    [")
    for start in range(0, len(twinkles), 6):
        w.append("        " + " ".join(f"0x{v:02X}," for v in twinkles[start : start + 6]))
    w.append("    ];")
    w.append("}")
    print("\n".join(w))


if __name__ == "__main__":
    main(sys.argv[1])
