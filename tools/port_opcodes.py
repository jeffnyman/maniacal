"""Generates OpcodeTable.g.cs from ScummVM's engines/scumm/script_v2.cpp.

Reads ScummEngine_v2::setupOpcodes: the handler of each of the 256 opcodes of versions 1 and 2.
Run from the repository root:

    python tools/port_opcodes.py ../scummvm/engines/scumm/script_v2.cpp > src/Maniacal.Scumm/Scripts/OpcodeTable.g.cs
"""

import re
import sys


def main(path):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()

    body = re.search(r"void ScummEngine_v2::setupOpcodes\(\) \{(.*?)\n\}", source, re.S).group(1)
    table = {int(op, 16): name for op, name in re.findall(r"OPCODE\((0x[0-9a-fA-F]{2}), (\w+)\);", body)}
    if sorted(table) != list(range(256)):
        sys.exit(f"setupOpcodes defines {len(table)} opcodes, not 256")

    print("// <auto-generated>")
    print("// Generated by tools/port_opcodes.py from ScummVM's engines/scumm/script_v2.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Scripts;")
    print()
    print("internal static class OpcodeTable")
    print("{")
    print("    /// <summary>The ScummVM handler of each opcode of versions 1 and 2. Mirrors <c>ScummEngine_v2::setupOpcodes</c>.</summary>")
    print("    public static readonly string[] Handlers =")
    print("    [")
    for op in range(256):
        print(f'        "{table[op]}", // 0x{op:02X}')
    print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
