"""Generates OpcodeTable.g.cs from ScummVM's engines/scumm/script_v2.cpp and script_v0.cpp.

Reads ScummEngine_v2::setupOpcodes, the handler of each of the 256 opcodes of versions 1 and 2,
and ScummEngine_v0::setupOpcodes, the C64's. Run from the repository root:

    python tools/port_opcodes.py ../scummvm/engines/scumm/script_v2.cpp ../scummvm/engines/scumm/script_v0.cpp > src/Maniacal.Scumm/Scripts/OpcodeTable.g.cs
"""

import re
import sys


def read_table(path, engine):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()

    body = re.search(r"void " + engine + r"::setupOpcodes\(\) \{(.*?)\n\}", source, re.S).group(1)
    table = {int(op, 16): name for op, name in re.findall(r"OPCODE\((0x[0-9a-fA-F]{2}), (\w+)\);", body)}
    if sorted(table) != list(range(256)):
        sys.exit(f"{engine}::setupOpcodes defines {len(table)} opcodes, not 256")
    return table


def print_table(field, summary, table):
    print(f"    /// <summary>{summary}</summary>")
    print(f"    public static readonly string[] {field} =")
    print("    [")
    for op in range(256):
        print(f'        "{table[op]}", // 0x{op:02X}')
    print("    ];")


def main(v2_path, v0_path):
    v2 = read_table(v2_path, "ScummEngine_v2")
    v0 = read_table(v0_path, "ScummEngine_v0")

    print("// <auto-generated>")
    print("// Generated by tools/port_opcodes.py from ScummVM's engines/scumm/script_v2.cpp and script_v0.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Scripts;")
    print()
    print("internal static class OpcodeTable")
    print("{")
    print_table("Handlers", "The ScummVM handler of each opcode of versions 1 and 2. Mirrors <c>ScummEngine_v2::setupOpcodes</c>.", v2)
    print()
    print_table("HandlersV0", "The ScummVM handler of each opcode of version 0, the C64's. Mirrors <c>ScummEngine_v0::setupOpcodes</c>.", v0)
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
