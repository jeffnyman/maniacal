"""Generates V0Actors.g.cs from ScummVM's engines/scumm/actor.cpp and costume.cpp.

Keeps the tables the C64's engine has for its actors rather than its scripts: their names
(v0ActorNames_English and v0ActorNames_German, read by getActorName), talk colours
(v0MMActorTalkColor, set by resetV1ActorTalkColor), talk flags (v0ActorTalk, set by
Actor_v0::initActor for the full game), costume colours (actorV0Colors, read by V0CostumeRenderer::drawLimb)
and how far the slanted walkboxes narrow at each line (v0WalkboxSlantedModifier, read by
adjustPosInBorderWalkbox). Run from the repository root:

    python tools/port_v0_actors.py ../scummvm/engines/scumm/actor.cpp ../scummvm/engines/scumm/costume.cpp > src/Maniacal.Scumm/Game/V0Actors.g.cs
"""

import re
import sys

BYTES = [
    ("v0ActorTalk", "Talk", 25, "What each actor's mouth does as it talks: bit 7 none, bit 6 no talking animation (<c>v0ActorTalk</c>)."),
    ("v0MMActorTalkColor", "TalkColors", 25, "The colour each actor's words are in (<c>v0MMActorTalkColor</c>)."),
    ("v0WalkboxSlantedModifier", "SlantedModifier", 0x16, "How many columns a slanted walkbox narrows by, line by line from its top (<c>v0WalkboxSlantedModifier</c>)."),
]
COLORS = ("actorV0Colors", "CostumeColors", 25, "The colour each actor's costume takes for its own (<c>actorV0Colors</c>).")
NAMES = [("v0ActorNames_English", "NamesEnglish", "English"), ("v0ActorNames_German", "NamesGerman", "German")]


def body(source, name):
    match = re.search(r"\b" + name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S)
    if match is None:
        sys.exit(f"{name} not found")
    return re.sub(r"//[^\n]*", "", match.group(1))


def numbers(source, name, count):
    values = [int(v, 0) for v in re.findall(r"\b(0x[0-9A-Fa-f]+|\d+)\b", body(source, name))]
    if len(values) != count:
        sys.exit(f"{name} has {len(values)} values, not {count}")
    return values


def emit_bytes(field, values, summary):
    print(f"    /// <summary>{summary}</summary>")
    print(f"    public static readonly byte[] {field} =")
    print("    [")
    for i in range(0, len(values), 8):
        print("        " + " ".join(f"0x{v:02X}," for v in values[i:i + 8]))
    print("    ];")


def main(actor_path, costume_path):
    with open(actor_path, encoding="utf-8") as f:
        actor = f.read()
    with open(costume_path, encoding="utf-8") as f:
        costume = f.read()

    print("// <auto-generated>")
    print("// Generated by tools/port_v0_actors.py from ScummVM's engines/scumm/actor.cpp and costume.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Game;")
    print()
    print("internal static class V0Actors")
    print("{")
    for table, field, count, summary in BYTES:
        emit_bytes(field, numbers(actor, table, count), summary)
        print()

    table, field, count, summary = COLORS
    emit_bytes(field, numbers(costume, table, count), summary)

    for table, field, language in NAMES:
        names = re.findall(r"\"([^\"]*)\"", body(actor, table))
        if len(names) != 24:
            sys.exit(f"{table} has {len(names)} names, not 24")
        print()
        print(f"    /// <summary>The names of actors 1 to 24 in {language}, empty for those with none (<c>{table}</c>).</summary>")
        print(f"    public static readonly string[] {field} =")
        print("    [")
        for name in names:
            print(f'        "{name}",')
        print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
