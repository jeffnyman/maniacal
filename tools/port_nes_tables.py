"""Generates NesTables.g.cs from ScummVM's engines/scumm/file_nes.cpp.

Keeps what ScummNESFile needs to see the NES cartridge as the DOS releases' room files: the MD5
of each of the seven ROMs it knows, where each resource lies in each ROM, and which resources
each room file holds, in order. Run from the repository root:

    python tools/port_nes_tables.py ../scummvm/engines/scumm/file_nes.cpp > src/Maniacal.Scumm/Resources/NesTables.g.cs
"""

import re
import sys

# the ROM sets, in ScummNESFile::ROMset's order
ROMSETS = ["usa", "eur", "swe", "fra", "ger", "esp", "ita"]
ROMSET_NAMES = ["USA", "Europe", "Sweden", "France", "Germany", "Spain", "Italy"]

# ScummNESFile::ResType, as NesResourceKind names it
KINDS = {
    "NES_GLOBDATA": "GlobalData",
    "NES_ROOM": "Room",
    "NES_SCRIPT": "Script",
    "NES_SOUND": "Sound",
    "NES_COSTUME": "Costume",
    "NES_ROOMGFX": "RoomGraphics",
    "NES_COSTUMEGFX": "CostumeGraphics",
    "NES_SPRPALS": "SpritePalettes",
    "NES_SPRDESC": "SpriteDescriptions",
    "NES_SPRLENS": "SpriteLengths",
    "NES_SPROFFS": "SpriteOffsets",
    "NES_SPRDATA": "SpriteData",
    "NES_CHARSET": "Charset",
    "NES_PREPLIST": "PrepositionList",
    "NES_TITLES": "Titles",
    "NES_TITLE2_SPARKLECHR": "TitleSparkleTiles",
    "NES_TITLE2_SPARKLEPAL": "TitleSparklePalette",
}

NUMBER = r"(0x[0-9A-Fa-f]+|\d+)"


def number(text):
    return int(text, 0)


def resources(source):
    """res_<group>_<romset>[n] = { {offset, length}, ... }, padded with empty entries to n."""
    found = {}
    pattern = r"Resource\s+res_(\w+?)_(" + "|".join(ROMSETS) + r")\[(\d+)\]\s*=\s*\{(.*?)\};"
    for group, romset, size, body in re.findall(pattern, source, re.DOTALL):
        pairs = [
            (number(a), number(b))
            for a, b in re.findall(r"\{\s*" + NUMBER + r"\s*,\s*" + NUMBER + r"\s*\}", body)
        ]
        size = int(size)
        if len(pairs) > size:
            sys.exit(f"res_{group}_{romset} has more entries than its size")
        found.setdefault(group, {})[romset] = pairs + [(0, 0)] * (size - len(pairs))
    return found


def kinds(source):
    """res_<group> = { ScummNESFile::NES_<kind>, ... }"""
    pattern = r"ResourceGroup\s+res_(\w+)\s*=\s*\{\s*ScummNESFile::(NES_\w+)"
    return {group: KINDS[kind] for group, kind in re.findall(pattern, source)}


def files(source):
    """lfl_NN[] = { {&res_<group>, index}, ..., {nullptr, 0} }"""
    found = {}
    for number_text, body in re.findall(r"LFLEntry\s+lfl_(\d+)\[\]\s*=\s*\{(.*?)\};", source, re.DOTALL):
        found[int(number_text)] = [(group, int(index)) for group, index in re.findall(r"&res_(\w+)\s*,\s*(\d+)", body)]
    return found


def rom_md5s(source):
    md5s = re.findall(r'md5str == "([0-9a-f]{32})"', source)
    if len(md5s) != len(ROMSETS):
        sys.exit(f"expected {len(ROMSETS)} ROM MD5s, found {len(md5s)}")
    return md5s


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    groups = resources(source)
    group_kinds = kinds(source)
    lfls = files(source)
    md5s = rom_md5s(source)

    for group in groups:
        if group not in group_kinds:
            sys.exit(f"res_{group} has no resource type")
        if sorted(groups[group]) != sorted(ROMSETS):
            sys.exit(f"res_{group} lacks a ROM set")

    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by tools/port_nes_tables.py from ScummVM's engines/scumm/file_nes.cpp. Do not edit.")
    w("// </auto-generated>")
    w("")
    w("namespace Maniacal.Scumm.Resources;")
    w("")
    w("/// <summary>The kinds of resource on the NES cartridge (<c>ScummNESFile::ResType</c>).</summary>")
    w("internal enum NesResourceKind")
    w("{")
    for kind in KINDS.values():
        w(f"    {kind},")
    w("}")
    w("")
    w("internal static class NesTables")
    w("{")
    w("    /// <summary>The ROM sets, in <c>ScummNESFile::ROMset</c>'s order.</summary>")
    w("    public static readonly string[] RomSets = [" + ", ".join(f'"{n}"' for n in ROMSET_NAMES) + "];")
    w("")
    w("    /// <summary>The MD5 of each ROM set's program data, the cartridge without its iNES header (<c>ScummNESFile::open</c>).</summary>")
    w("    public static readonly string[] RomMd5 =")
    w("    [")
    for md5 in md5s:
        w(f'        "{md5}",')
    w("    ];")

    for group in groups:
        field = group_kinds[group]
        w("")
        w(f"    /// <summary>Where each <c>res_{group}</c> resource lies in each ROM set: its offset in the program data and its length.</summary>")
        w(f"    public static readonly (int Offset, int Length)[][] {field} =")
        w("    [")
        for romset in ROMSETS:
            entries = groups[group][romset]
            w("        [")
            for start in range(0, len(entries), 6):
                w("            " + " ".join(f"(0x{o:05X}, 0x{l:04X})," for o, l in entries[start : start + 6]))
            w("        ],")
        w("    ];")

    w("")
    w("    /// <summary>The resources of a group, by ROM set.</summary>")
    w("    public static (int Offset, int Length)[][] Group(NesResourceKind kind) => kind switch")
    w("    {")
    for group in groups:
        field = group_kinds[group]
        w(f"        NesResourceKind.{group_kinds[group]} => {field},")
    w('        _ => throw new ArgumentOutOfRangeException(nameof(kind)),')
    w("    };")

    w("")
    w("    /// <summary>")
    w("    /// The resources each room file holds, in order: file 1 at index 1 (<c>lfls</c>). File 0 is")
    w("    /// the index, built from them all.")
    w("    /// </summary>")
    w("    public static readonly (NesResourceKind Kind, int Index)[][] Files =")
    w("    [")
    w("        [],")
    for n in range(1, max(lfls) + 1):
        if n not in lfls:
            sys.exit(f"lfl_{n:02d} missing")
        w(f"        [{', '.join(f'(NesResourceKind.{group_kinds[g]}, {i})' for g, i in lfls[n])}],")
    w("    ];")
    w("}")

    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
