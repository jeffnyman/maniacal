"""Generates V0Verbs.g.cs from ScummVM's engines/scumm/verbs.cpp and verbs.h.

Keeps the C64's verbs, which its engine makes itself rather than its scripts (v0VerbTable_English
and v0VerbTable_German, read by ScummEngine_v0::resetVerbs): each verb's number, its column and
row, and its name. Run from the repository root:

    python tools/port_v0_verbs.py ../scummvm/engines/scumm/verbs.cpp ../scummvm/engines/scumm/verbs.h > src/Maniacal.Scumm/Game/V0Verbs.g.cs
"""

import re
import sys

TABLES = [("v0VerbTable_English", "English"), ("v0VerbTable_German", "German")]


def main(source_path, header_path):
    with open(source_path, encoding="utf-8") as f:
        source = f.read()
    with open(header_path, encoding="utf-8") as f:
        header = f.read()

    enum = re.search(r"enum VerbsV0 \{(.*?)\};", header, re.S).group(1)
    ids = {name: int(value) for name, value in re.findall(r"(kVerb\w+)\s*=\s*(\d+)", enum)}

    print("// <auto-generated>")
    print("// Generated by tools/port_v0_verbs.py from ScummVM's engines/scumm/verbs.cpp and verbs.h. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Game;")
    print()
    print("internal static class V0Verbs")
    print("{")
    for i, (table, field) in enumerate(TABLES):
        body = re.search(r"\b" + table + r"\[\]\s*=\s*\{(.*?)\n\};", source, re.S).group(1)
        rows = re.findall(r"\{\s*(kVerb\w+),\s*(\d+),\s*(\d+),\s*\"([^\"]*)\"\s*\}", body)
        if len(rows) != 15:
            sys.exit(f"{table} has {len(rows)} verbs, not 15")
        if i > 0:
            print()
        print(f"    /// <summary>The verbs in {field}: number, column, row and name (<c>{table}</c>).</summary>")
        print(f"    public static readonly (int Id, int Column, int Row, string Name)[] {field} =")
        print("    [")
        for name, column, row, text in rows:
            print(f'        ({ids[name]}, {column}, {row}, "{text}"),')
        print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
