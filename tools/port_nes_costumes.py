"""Generates NesCostumeTables.g.cs from ScummVM's engines/scumm/costume.cpp and gfx.cpp.

Keeps what the NES's costumes and dark rooms are drawn with: the costume numbers' places in the
costume sets' descriptions (v1MMNESLookup), the costume slots of each set's parts
(v1MMNEScostTables), and the two dark palettes, the rooms' (drawStripNES) and the actors'
(NESCostumeRenderer::drawLimb). Run from the repository root:

    python tools/port_nes_costumes.py ../scummvm/engines/scumm > src/Maniacal.Scumm/Costumes/NesCostumeTables.g.cs
"""

import os
import re
import sys


def read(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as file:
        return file.read()


def numbers(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    return [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\d+", text)]


def table(source, pattern, name):
    match = re.search(pattern, source, re.DOTALL)
    if match is None:
        sys.exit(f"{name} not found")
    return numbers(match.group(1))


def main(folder):
    costume = read(folder, "costume.cpp")
    gfx = read(folder, "gfx.cpp")

    lookup = table(costume, r"v1MMNESLookup\[25\]\s*=\s*\{(.*?)\};", "v1MMNESLookup")
    sets = table(gfx, r"v1MMNEScostTables\[2\]\[6\]\s*=\s*\{(.*?)\n\};", "v1MMNEScostTables")
    room_dark = table(gfx, r"drawStripNES\(.*?darkPalette\[16\]\s*=\s*\{(.*?)\};", "drawStripNES's darkPalette")
    actor_dark = table(costume, r"NESCostumeRenderer::drawLimb\(.*?darkpalette\[16\]\s*=\s*\{(.*?)\};", "drawLimb's darkpalette")

    if len(lookup) != 25 or len(sets) != 12 or len(room_dark) != 16 or len(actor_dark) != 16:
        sys.exit("a table has the wrong size")

    def bytes_line(values):
        return " ".join(f"0x{v:02X}," for v in values)

    out = [
        "// <auto-generated>",
        "// Generated by tools/port_nes_costumes.py from ScummVM's engines/scumm/costume.cpp and gfx.cpp. Do not edit.",
        "// </auto-generated>",
        "",
        "namespace Maniacal.Scumm.Costumes;",
        "",
        "internal static class NesCostumeTables",
        "{",
        "    /// <summary>Each costume's place in its set's descriptions (<c>v1MMNESLookup</c>).</summary>",
        "    public static readonly int[] Lookup =",
        "    [",
        "        " + " ".join(f"{v}," for v in lookup),
        "    ];",
        "",
        "    /// <summary>",
        "    /// The costume slots of each set's parts: descriptions, lengths, offsets, sprite data, tiles",
        "    /// and palette (<c>v1MMNEScostTables</c>).",
        "    /// </summary>",
        "    public static readonly int[][] Sets =",
        "    [",
        "        [" + ", ".join(str(v) for v in sets[:6]) + "],",
        "        [" + ", ".join(str(v) for v in sets[6:]) + "],",
        "    ];",
        "",
        "    /// <summary>The colours of a room without its lights (<c>drawStripNES</c>'s <c>darkPalette</c>).</summary>",
        "    public static ReadOnlySpan<byte> DarkRoomPalette => [" + bytes_line(room_dark).rstrip(",") + "];",
        "",
        "    /// <summary>The colours of an actor without the light's colours (<c>NESCostumeRenderer::drawLimb</c>'s <c>darkpalette</c>).</summary>",
        "    public static ReadOnlySpan<byte> DarkActorPalette => [" + bytes_line(actor_dark).rstrip(",") + "];",
        "}",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
