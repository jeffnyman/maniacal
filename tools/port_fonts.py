"""Generates FontData.g.cs from ScummVM's engines/scumm/charset-fontdata.cpp.

Ports the English font of versions 1 and 2 (englishCharsetDataV2) and the glyph table its
replacements come from (specialCharsetData). Run from the repository root:

    python tools/port_fonts.py ../scummvm/engines/scumm/charset-fontdata.cpp > src/Maniacal.Scumm/Graphics/FontData.g.cs
"""

import re
import sys

ARRAYS = {
    "englishCharsetDataV2": "EnglishV2",
    "specialCharsetData": "Special",
}


def extract(source, name):
    match = re.search(r"static const byte " + name + r"\[\] = \{(.*?)\};", source, re.S)
    if not match:
        sys.exit(f"{name} not found")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    return [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", body)]


def main(path):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()

    print("// <auto-generated>")
    print("// Generated by tools/port_fonts.py from ScummVM's engines/scumm/charset-fontdata.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Graphics;")
    print()
    print("internal static class FontData")
    print("{")
    for scumm_name, name in ARRAYS.items():
        values = extract(source, scumm_name)
        if len(values) % 8:
            sys.exit(f"{scumm_name} has {len(values)} bytes, not a whole number of 8-byte glyphs")
        print(f"    /// <summary>Mirrors <c>{scumm_name}</c>: {len(values) // 8} glyphs of 8 rows.</summary>")
        print(f"    public static ReadOnlySpan<byte> {name} =>")
        print("    [")
        for i in range(0, len(values), 8):
            row = ", ".join(f"0x{v:02X}" for v in values[i:i + 8])
            print(f"        {row},")
        print("    ];")
        print()
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
