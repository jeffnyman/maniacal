"""Generates TransitionEffects.g.cs from ScummVM's engines/scumm/gfx.cpp.

Ports transitionEffects, the room transitions of transitionEffect: for each, its number of
iterations (which versions before 3 work out from the screen's height instead), and the four lines
of 8x8 blocks it updates, each line's left, top, right and bottom block and how far each moves an
iteration. Run from the repository root:

    python tools/port_transitions.py ../scummvm/engines/scumm/gfx.cpp > src/Maniacal.Scumm/Graphics/TransitionEffects.g.cs
"""

import re
import sys

NAMES = ["Iris", "BoxWipeDownRight", "BoxWipeUpLeft", "InverseBoxWipe", "InverseIris", "HorizontalWipe"]


def main(path):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()
    match = re.search(r"static const TransitionEffect transitionEffects\[6\] = \{(.*?)\n\};", source, re.S)
    if not match:
        sys.exit("transitionEffects not found")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    values = [int(v) for v in re.findall(r"-?\d+", body)]
    if len(values) != 6 * 33:
        sys.exit(f"transitionEffects has {len(values)} values, not {6 * 33}")

    print("// <auto-generated>")
    print("// Generated by tools/port_transitions.py from ScummVM's engines/scumm/gfx.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Graphics;")
    print()
    print("internal static class TransitionEffects")
    print("{")
    print("    /// <summary>")
    print("    /// Mirrors <c>transitionEffects</c>: iris, box wipes from the top left and the bottom right, inverse box")
    print("    /// wipe, the inverse iris of versions 1 and 2, and the NES's horizontal wipe. Each is its iterations, then")
    print("    /// 16 deltas and 16 starts: left, top, right and bottom, in 8x8 blocks, of four lines; a start of 24 is the")
    print("    /// screen's last row of blocks.")
    print("    /// </summary>")
    print("    public static readonly (int Iterations, int[] Deltas, int[] Starts)[] All =")
    print("    [")
    for i in range(6):
        chunk = values[i * 33:(i + 1) * 33]
        deltas = ", ".join(str(v) for v in chunk[1:17])
        starts = ", ".join(str(v) for v in chunk[17:33])
        print(f"        // {NAMES[i]}")
        print(f"        ({chunk[0]}, [{deltas}], [{starts}]),")
    print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
