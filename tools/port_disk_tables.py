"""Generates C64DiskTables.g.cs from ScummVM's engines/scumm/file.cpp.

Keeps the tables ScummDiskImage needs for Maniac Mansion on the C64: how many resources each
room file holds (the full game and the demo), and where each track starts on a disk, in sectors.
Run from the repository root:

    python tools/port_disk_tables.py ../scummvm/engines/scumm/file.cpp > src/Maniacal.Scumm/Resources/C64DiskTables.g.cs
"""

import re
import sys

TABLES = [
    ("maniacResourcesPerFile", "ResourcesPerFile", "The resources in each room file of the full game (<c>maniacResourcesPerFile</c>)."),
    ("maniacDemoResourcesPerFile", "DemoResourcesPerFile", "The resources in each room file of the demo (<c>maniacDemoResourcesPerFile</c>)."),
    ("C64SectorOffset", "TrackStarts", "The first sector of each track of a disk, track 1 at index 1 (<c>C64SectorOffset</c>)."),
]


def table(source, name):
    match = re.search(r"\b" + name + r"\[\d+\]\s*=\s*\{([^}]*)\}", source)
    if match is None:
        sys.exit(f"{name} not found")
    return [int(value) for value in re.findall(r"\d+", match.group(1))]


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    print("// <auto-generated>")
    print("// Generated by tools/port_disk_tables.py from ScummVM's engines/scumm/file.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Resources;")
    print()
    print("internal static class C64DiskTables")
    print("{")
    for i, (name, field, summary) in enumerate(TABLES):
        values = table(source, name)
        if i > 0:
            print()
        print(f"    /// <summary>{summary}</summary>")
        print(f"    public static readonly int[] {field} =")
        print("    [")
        for start in range(0, len(values), 12):
            print("        " + " ".join(f"{v}," for v in values[start:start + 12]))
        print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
