"""Generates SoundTables.g.cs from ScummVM's engines/scumm/players/player_v2base.cpp.

Ports the tables of the version 1 and 2 PC speaker and PCjr music player: the note lengths, the
volume hulls and where each starts, the frequency modulation curves, and the two frequency tables.
Run from the repository root:

    python tools/port_sound_tables.py ../scummvm/engines/scumm/players/player_v2base.cpp > src/Maniacal.Scumm/Sound/SoundTables.g.cs
"""

import re
import sys

# ScummVM name: (C# name, C# element type, summary)
ARRAYS = {
    "note_lengths": ("NoteLengths", "byte", "how many tempo units each note length code lasts"),
    "hull_offsets": ("HullOffsets", "ushort", "where each volume hull starts in <see cref=\"Hulls\"/>"),
    "hulls": ("Hulls", "short", "the volume hulls: pairs of a value and a count, -1 setting the volume at once"),
    "freqmod_lengths": ("FreqmodLengths", "ushort", "the length of each frequency modulation curve"),
    "freqmod_offsets": ("FreqmodOffsets", "ushort", "where each frequency modulation curve starts in <see cref=\"FreqmodTable\"/>"),
    "freqmod_table": ("FreqmodTable", "sbyte", "the frequency modulation curves: a sine, a saw, a square and noise"),
    "spk_freq_table": ("SpeakerFrequencies", "ushort", "the PC speaker timer divisors of the 12 notes of the lowest octave"),
    "pcjr_freq_table": ("PcjrFrequencies", "ushort", "the PCjr divisors of the 12 notes of the lowest octave, times 64"),
}

WIDTHS = {"byte": (8, False), "ushort": (16, False), "short": (16, True), "sbyte": (8, True)}


def wrap(value, element):
    bits, signed = WIDTHS[element]
    value &= (1 << bits) - 1
    if signed and value >= 1 << (bits - 1):
        value -= 1 << bits
    return value


def extract(source, name, element):
    match = re.search(r"(?:static )?const \w+ +" + name + r"\[[^\]]*\] = \{(.*?)\};", source, re.S)
    if not match:
        sys.exit(f"{name} not found")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    values = []
    for item in body.split(","):
        item = item.replace("(int16)", "").replace(" ", "").strip()
        if item:
            values.append(wrap(int(item, 0), element))
    return values


def main(path):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()

    print("// <auto-generated>")
    print("// Generated by tools/port_sound_tables.py from ScummVM's engines/scumm/players/player_v2base.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Sound;")
    print()
    print("internal static class SoundTables")
    print("{")
    for scumm_name, (name, element, summary) in ARRAYS.items():
        values = extract(source, scumm_name, element)
        print(f"    /// <summary>Mirrors <c>{scumm_name}</c>, {len(values)} entries: {summary}.</summary>")
        print(f"    public static ReadOnlySpan<{element}> {name} =>")
        print("    [")
        for i in range(0, len(values), 8):
            print("        " + ", ".join(str(v) for v in values[i:i + 8]) + ",")
        print("    ];")
        print()
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
