"""Generates V2aSoundTables.g.cs from ScummVM's engines/scumm/players/player_v2a.cpp.

Keeps the table Player_V2A knows the Amiga's sounds by (findSound): for each of Maniac Mansion's
sounds, the CRC of its data, the class that plays it and the class's arguments (offsets, sizes,
periods, volumes, durations), as ScummVM writes them. Zak McKracken's are left out. Run from the
repository root:

    python tools/port_v2a_sounds.py ../scummvm/engines/scumm/players/player_v2a.cpp > src/Maniacal.Scumm/Sound/V2aSoundTables.g.cs
"""

import re
import sys

# a backslash, as the C++ byte strings write one
BS = chr(92)

# ScummVM's classes, as V2aKind names them
KINDS = {
    "V2A_Sound_Single": "Single",
    "V2A_Sound_SingleLooped": "SingleLooped",
    "V2A_Sound_MultiLooped": "MultiLooped",
    "V2A_Sound_MultiLoopedDuration": "MultiLoopedDuration",
    "V2A_Sound_SingleLoopedPitchbend": "SingleLoopedPitchbend",
    "V2A_Sound_Special_Maniac69": "Maniac69",
    "V2A_Sound_Special_ManiacDing": "ManiacDing",
    "V2A_Sound_Special_ManiacTentacle": "ManiacTentacle",
    "V2A_Sound_Special_Maniac59": "Maniac59",
    "V2A_Sound_Special_Maniac61": "Maniac61",
    "V2A_Sound_Special_ManiacPhone": "ManiacPhone",
    "V2A_Sound_Special_Maniac46": "Maniac46",
    "V2A_Sound_Special_ManiacTypewriter": "ManiacTypewriter",
    "V2A_Sound_Special_Maniac32": "Maniac32",
    "V2A_Sound_Special_Maniac44": "Maniac44",
    "V2A_Sound_Music": "Music",
}


def arguments(text):
    """The arguments of a constructor call: numbers, a byte string, a boolean."""
    numbers, durations, flag = [], None, False
    string = re.search('"((?:' + BS + BS + 'x[0-9A-Fa-f]{2})*)"', text)
    if string:
        durations = [int(h, 16) for h in re.findall(BS + BS + "x([0-9A-Fa-f]{2})", string.group(1))]
        text = text[: string.start()] + text[string.end():]
        text = text.replace("(const uint8 *)", "")
    for part in [p.strip() for p in text.split(",")]:
        if part in ("true", "false"):
            flag = part == "true"
        elif part:
            numbers.append(int(part, 0))
    return numbers, durations, flag


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    pattern = r"CRCToSound\((0x[0-9A-Fa-f]{8}),\s*(V2A_\w+)\((.*?)\)\);\s*//\s*Maniac (\d+)"
    rows = []
    for crc, cls, args, sound in re.findall(pattern, source):
        if cls not in KINDS:
            sys.exit(f"{cls} is not a class Maniacal ports")
        numbers, durations, flag = arguments(args)
        rows.append((int(crc, 16), KINDS[cls], numbers, durations, flag, int(sound)))
    if len(rows) != 41:
        sys.exit(f"expected Maniac Mansion's 41 sounds, found {len(rows)}")

    out = [
        "// <auto-generated>",
        "// Generated by tools/port_v2a_sounds.py from ScummVM's engines/scumm/players/player_v2a.cpp. Do not edit.",
        "// </auto-generated>",
        "",
        "#nullable enable",
        "",
        "namespace Maniacal.Scumm.Sound;",
        "",
        "/// <summary>The classes Player_V2A plays Maniac Mansion's Amiga sounds with.</summary>",
        "internal enum V2aKind",
        "{",
    ]
    for kind in KINDS.values():
        out.append(f"    {kind},")
    out += [
        "}",
        "",
        "/// <summary>A sound of the table: the CRC of its data, its class, the class's numbers, durations and flag, and the sound's number in the game.</summary>",
        "internal sealed record V2aSoundEntry(uint Crc, V2aKind Kind, int[] Args, byte[]? Durations, bool Flag, int Sound);",
        "",
        "internal static class V2aSoundTables",
        "{",
        "    /// <summary>Maniac Mansion's sounds as <c>findSound</c> knows them, in its order.</summary>",
        "    public static readonly V2aSoundEntry[] Sounds =",
        "    [",
    ]
    for crc, kind, numbers, durations, flag, sound in rows:
        args = ", ".join(f"0x{n:04X}" for n in numbers)
        durs = "null" if durations is None else "[" + ", ".join(f"0x{d:02X}" for d in durations) + "]"
        out.append(f"        new(0x{crc:08X}, V2aKind.{kind}, [{args}], {durs}, {'true' if flag else 'false'}, {sound}),")
    out += ["    ];", "}"]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
