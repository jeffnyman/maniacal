"""Generates NesSoundTables.g.cs from ScummVM's engines/scumm/players/player_nes.cpp.

Keeps the tables Player_NES plays the NES's music and sound effects with, and those of its
emulation of the NES's sound chip (APUe): note pitches, the instruments' channels and commands,
the command chains, the length counter's loads, the square channels' duty cycles, the triangle's
steps and the noise channel's periods. Run from the repository root:

    python tools/port_nes_sound.py ../scummvm/engines/scumm/players/player_nes.cpp > src/Maniacal.Scumm/Sound/NesSoundTables.g.cs
"""

import re
import sys

# ScummVM's name, its size, the C# name and type, and what it is
TABLES = [
    ("freqTable", "64", "Pitches", "ushort", "The square and triangle channels' periods for the 64 notes (<c>freqTable</c>)."),
    ("instChannel", "16", "InstrumentChannels", "byte", "The channel each instrument plays on (<c>instChannel</c>)."),
    ("startCmd", "16", "StartCommands", "byte", "The command an instrument's note starts with (<c>startCmd</c>)."),
    ("releaseCmd", "16", "ReleaseCommands", "byte", "The command an instrument's note is released with (<c>releaseCmd</c>)."),
    ("nextCmd", "28", "NextCommands", "byte", "The command each command leads to, 0xFF for none (<c>nextCmd</c>)."),
    ("nextDelay", "28", "NextDelays", "byte", "The frames before each command's next (<c>nextDelay</c>)."),
    ("LengthCounts", "32", "LengthCounts", "byte", "The length counter's loads (<c>APUe::LengthCounts</c>)."),
    ("Duties", "4][8", "Duties", "sbyte", "The square channels' four duty cycles, eight steps each, row after row (<c>APUe::Duties</c>)."),
    ("TriDuty", "32", "TriangleSteps", "sbyte", "The triangle channel's 32 steps (<c>APUe::TriDuty</c>)."),
    ("NoiseFreq", "16", "NoisePeriods", "int", "The noise channel's 16 periods (<c>APUe::NoiseFreq</c>)."),
]


def values(source, name, size):
    match = re.search(r"\b" + re.escape(name) + r"\[" + re.escape(size) + r"\]\s*=\s*\{(.*?)\};", source, re.DOTALL)
    if match is None:
        sys.exit(f"{name} not found")
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", match.group(1), flags=re.DOTALL)
    return [int(v, 0) for v in re.findall(r"[+-]?(?:0x[0-9A-Fa-f]+|\d+)", text)]


def main(path):
    with open(path, encoding="utf-8") as file:
        source = file.read()

    out = [
        "// <auto-generated>",
        "// Generated by tools/port_nes_sound.py from ScummVM's engines/scumm/players/player_nes.cpp. Do not edit.",
        "// </auto-generated>",
        "",
        "namespace Maniacal.Scumm.Sound;",
        "",
        "internal static class NesSoundTables",
        "{",
    ]
    for i, (name, size, field, kind, summary) in enumerate(TABLES):
        numbers = values(source, name, size)
        expected = 32 if size == "4][8" else int(size)
        if len(numbers) != expected:
            sys.exit(f"{name} has {len(numbers)} values, not {expected}")
        if i > 0:
            out.append("")
        out.append(f"    /// <summary>{summary}</summary>")
        out.append(f"    public static readonly {kind}[] {field} =")
        out.append("    [")
        for start in range(0, len(numbers), 8):
            row = numbers[start : start + 8]
            if kind in ("byte", "ushort"):
                out.append("        " + " ".join(f"0x{v:02X}," for v in row))
            else:
                out.append("        " + " ".join(f"{v}," for v in row))
        out.append("    ];")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
