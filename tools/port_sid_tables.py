"""Generates SidTables.g.cs from ScummVM's SID emulator and its C64 music player.

Ports the tables of audio/softsynth/sid.cpp and wave6581.cpp (reSID's combined waveforms of the
MOS 6581, its filter cutoff curve, and the envelope's rates and sustain levels) and of
engines/scumm/players/player_sid.cpp (the NTSC note frequencies and the three channel buffers the
player starts with). Run from the repository root:

    python tools/port_sid_tables.py ../scummvm/audio/softsynth/sid.cpp ../scummvm/audio/softsynth/wave6581.cpp ../scummvm/engines/scumm/players/player_sid.cpp > src/Maniacal.Scumm/Sound/SidTables.g.cs
"""

import re
import sys

# (file index, ScummVM name, C# name, C# element type, expected count, summary)
ARRAYS = [
    (1, "wave6581__ST", "Wave6581ST", "byte", 4096, "the 6581's sawtooth and triangle combined, by accumulator's top 12 bits"),
    (1, "wave6581_P_T", "Wave6581PT", "byte", 4096, "the 6581's pulse and triangle combined, by the triangle's top 11 bits"),
    (1, "wave6581_PS_", "Wave6581PS", "byte", 4096, "the 6581's pulse and sawtooth combined"),
    (1, "wave6581_PST", "Wave6581PST", "byte", 4096, "the 6581's pulse, sawtooth and triangle combined"),
    (0, "f0_points_6581", "CutoffPoints6581", "ushort", 31 * 2, "the 6581's filter cutoff curve: pairs of the FC register and a frequency in Hz, end points repeated"),
    (0, "rate_counter_period", "RateCounterPeriods", "ushort", 16, "the envelope's cycles per step for each attack, decay and release rate"),
    (0, "sustain_level", "SustainLevels", "byte", 16, "the envelope counter of each sustain level"),
    (2, "FREQ_TBL", "NoteFrequencies", "ushort", 97, "the SID frequency of each note (tone * 2^24 / the NTSC clock), 0 for none"),
    (2, "chanBuffer_const", "ChannelBuffers", "byte", 3 * 45, "the three channel buffers the player starts with, 45 bytes each"),
]


def extract(source, name, count):
    match = re.search(r"\b" + name + r"\[[^=]*\] = \{(.*?)\};", source, re.S)
    if not match:
        sys.exit(f"{name} not found")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    values = [int(v, 0) for v in re.findall(r"\b(0x[0-9A-Fa-f]+|\d+)\b", body)]
    if len(values) != count:
        sys.exit(f"{name} has {len(values)} values, not {count}")
    return values


def main(paths):
    sources = []
    for path in paths:
        with open(path, encoding="utf-8") as handle:
            sources.append(handle.read())

    print("// <auto-generated>")
    print("// Generated by tools/port_sid_tables.py from ScummVM's audio/softsynth/sid.cpp, wave6581.cpp")
    print("// and engines/scumm/players/player_sid.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Maniacal.Scumm.Sound;")
    print()
    print("internal static class SidTables")
    print("{")
    for index, (source, scumm_name, name, element, count, summary) in enumerate(ARRAYS):
        values = extract(sources[source], scumm_name, count)
        if index > 0:
            print()
        print(f"    /// <summary>Mirrors <c>{scumm_name}</c>, {len(values)} entries: {summary}.</summary>")
        print(f"    public static ReadOnlySpan<{element}> {name} =>")
        print("    [")
        hexadecimal = element == "byte"
        for i in range(0, len(values), 16 if hexadecimal else 8):
            row = values[i:i + (16 if hexadecimal else 8)]
            print("        " + ", ".join(f"0x{v:02X}" if hexadecimal else str(v) for v in row) + ",")
        print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1:])
